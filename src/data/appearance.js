/**
 * 玩家的外观尺寸与判定尺寸——唯一来源。
 *
 * 这三件事必须永远一致，所以只允许在这里定义：
 *   1. 视觉帧画多大（FRAME_DRAW_H）
 *   2. 碰撞盒从脚底往上推多高（BOX_H）
 *   3. 子弹从哪儿出膛（MUZZLE_H）
 *
 * 为什么要单独一个文件：枪口高度既是**玩法参数**（决定贴脸时子弹是先出膛
 * 还是先命中），又要在渲染层用来摆技能条和阴影。放在渲染层里，update.js
 * 就得反向依赖 UI；放在 update.js 里，渲染层又会各自抄一份常量。
 *
 * ── 坐标约定（重要）──
 * player.y 是**脚底**（ground anchor），不是碰撞盒中心，也不是视觉中心。
 * 好处是"角色站在哪"只有一个答案：
 *   绘制锚点 = p.y
 *   碰撞盒   = p.y - p.h  ~  p.y      （底边贴脚底）
 *   枪口     = p.y - MUZZLE_H
 *   摄像机   = p.y - EYE_H
 * 之前 p.y 是碰撞盒中心、绘制锚点又是 p.y + 17，两个参考系错开 49px，
 * 表现为"敌人还没贴到脚就掉血"和"子弹从脚底冒出来"。
 */

/**
 * 序列帧模式下角色的视觉高度（像素）。
 *
 * 帧格子是 288×384，但角色 bbox 只占一部分，剩下是留白。
 * 想让角色本体看起来有约 98px 高，整帧就得画 116px —— 帧高 ≠ 角色高。
 *
 * 132 → 116：原来主角本体占屏高太多，和"割草"的视野感不搭——画面上
 * 只看得到自己，看不到战场。缩到 116 后本体约 98，与基准怪（体约 65）
 * 仍是 1.5 倍，"主角大、杂兵小"的可读性没有丢。
 */
export const FRAME_DRAW_H = 116;

/** 碰撞盒基准宽度。序列帧的视觉尺寸按 p.w / BASE_W 等比缩放，贝拉技能变大才生效 */
export const BASE_W = 40;

/** 碰撞盒高度：底边贴脚底，盒子覆盖"脚踝往上 44px"，也就是小腿到腰 */
export const BOX_H = 44;

/** 脚底到碰撞盒中心的距离（有一堆地方只需要这个偏移，懒得每次构造盒子） */
export const BOX_LIFT = BOX_H / 2;

/**
 * 枪口离脚底的高度。
 *
 * 不能按"真人胸口 = 55% 身高"算：Q 版是 2.5 头身，头加头发占掉大半个身高，
 * 55% 已经贴到下巴，子弹看着像从嘴里吐出来。取 40%（116 × 0.4 ≈ 46px），
 * 落在颈部以下的身体上半段。
 *
 * **写成派生值而不是绝对像素**：角色缩小/放大时枪口必须跟着起伏，
 * 否则会出现"角色变小了，子弹还在原来的高度"——表现为子弹从敌人头顶飞过。
 * 下限由碰撞盒顶沿（p.y - BOX_H = 脚底 − 44）压着，再低就变成贴着脚边射。
 */
export const MUZZLE_H = Math.round(FRAME_DRAW_H * 0.4);

/** 出膛点沿射击方向前移多远：让子弹从身前而不是身体轮廓里出现 */
export const MUZZLE_FWD = 18;

/**
 * 摄像机对准点离脚底的高度。取视觉身高的中点（116 × 0.44 ≈ 51），
 * 让角色整体看起来在屏幕正中。跟脚底会让角色视觉重心偏上半个身高，
 * 玩久了会觉得"画面一直在往下拖"。
 *
 * 同样写成派生值：角色尺寸一改，摄像机对准点自动跟上。
 */
export const EYE_H = Math.round(FRAME_DRAW_H * 0.44);

/**
 * 序列帧的"半宽 / 高"比例。格子是 384×512（3:4），帧内角色基本占满，
 * 所以视觉宽 ≈ 高 × 0.75，半宽 ≈ 高 × 0.375。
 *
 * 这个数是给**圆形范围判定**用的：碰撞盒只有 40 宽，而视觉有 99 宽，
 * 拿碰撞盒算距离会让敌人一路钻进角色身体里（实测贴到 22px，
 * 画面上玩家被完全盖住，找不到自己在哪）。
 */
export const SPRITE_HALF_W = 0.375;

/** 玩家视觉半宽（像素）。贝拉技能把 p.w 撑大时跟着放大 */
export function playerHalfW(p) {
  return FRAME_DRAW_H * (p.w / BASE_W) * SPRITE_HALF_W;
}

/**
 * 玩家的碰撞盒（世界坐标）。
 * 底边永远贴脚底，所以贝拉技能把 p.h 撑到 66 时盒子会往上长，而不是往下沉。
 */
export function playerBox(p) {
  return { x: p.x, y: p.y - p.h / 2, w: p.w, h: p.h };
}

/** 玩家身体中心（做圆形范围判定时用：反伤、拾取提示、受伤粒子） */
export function playerCenterY(p) {
  return p.y - p.h / 2;
}

/**
 * 子弹出生点。
 * @param {number} dx 射击方向单位向量 x（用于把出膛点推到身前）
 * @param {number} dy 射击方向单位向量 y
 */
export function muzzleOf(p, dx = 0, dy = 0) {
  return {
    x: p.x + dx * MUZZLE_FWD,
    y: p.y - MUZZLE_H + dy * MUZZLE_FWD,
  };
}
